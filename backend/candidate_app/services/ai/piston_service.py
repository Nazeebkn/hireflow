import ast

# ===== TIMING CHECK ADDED: START =====
import time

import requests

# ===== TIMING CHECK ADDED: END =====


PISTON_URL = "http://host.docker.internal:2000/api/v2/execute"


PISTON_VERSIONS = {
    "python": "3.12.0",
    "javascript": "20.11.1",
}


def _prepare_python_code(code, input_data):
    """
    Supports function-based Python coding questions.

    Example candidate code:

        def count_vowels(s):
            count = 0
            for char in s.lower():
                if char in "aeiou":
                    count += 1
            return count

    Input:
        Hello World

    Generated execution:

        def count_vowels(s):
            ...

        print(count_vowels("Hello World"))
    """

    try:
        tree = ast.parse(code)
    except SyntaxError:
        return code

    function_nodes = [
        node
        for node in tree.body
        if isinstance(node, ast.FunctionDef)
    ]

    if not function_nodes:
        return code

    function_name = function_nodes[0].name

    try:
        parsed_input = ast.literal_eval(input_data)
    except (ValueError, SyntaxError):
        parsed_input = input_data

    argument_repr = repr(parsed_input)

    wrapper = (
        f"\n\n"
        f"print({function_name}({argument_repr}))\n"
    )

    return f"{code.rstrip()}{wrapper}"


def _prepare_javascript_code(code, input_data):
    """
    Supports function-based JavaScript coding questions.

    Example candidate code:

        function findMax(arr) {
            return Math.max(...arr);
        }

    Input:

        [1, 5, 3, 9, 2]

    Generated execution:

        function findMax(arr) {
            ...
        }

        console.log(findMax([1, 5, 3, 9, 2]));
    """

    import re

    function_match = re.search(
        r"\bfunction\s+([A-Za-z\_$][A-Za-z0-9\_$]*)\s*\(",
        code,
    )

    if not function_match:
        return code

    function_name = function_match.group(1)

    input_value = str(input_data).strip()

    # JavaScript test inputs generated by Gemini
    # should already be valid JavaScript values.
    argument = input_value

    wrapper = (
        f"\n\n"
        f"console.log({function_name}({argument}));\n"
    )

    return f"{code.rstrip()}{wrapper}"


def _prepare_code(
    code,
    input_data,
    language,
):
    language = language.lower()

    if language == "python":
        return _prepare_python_code(
            code=code,
            input_data=input_data,
        )

    if language == "javascript":
        return _prepare_javascript_code(
            code=code,
            input_data=input_data,
        )

    return code


def execute_code(
    code,
    language="python",
    version=None,
    input_data="",
):
    language = language.lower()

    if language not in PISTON_VERSIONS:
        raise ValueError(
            f"Unsupported programming language: {language}"
        )

    if version is None:
        version = PISTON_VERSIONS[language]

    execution_code = _prepare_code(
        code=code,
        input_data=input_data,
        language=language,
    )

    filename = (
        "main.py"
        if language == "python"
        else "main.js"
    )

    response = requests.post(
        PISTON_URL,
        json={
            "language": language,
            "version": version,
            "files": [
                {
                    "name": filename,
                    "content": execution_code,
                }
            ],
            "stdin": "",
        },
        timeout=10,
    )

    response.raise_for_status()

    return response.json()


def execute_test_cases(
    code,
    test_cases,
    language="python",
    version=None,
):
    language = language.lower()

    if language not in PISTON_VERSIONS:
        raise ValueError(
            f"Unsupported programming language: {language}"
        )

    if version is None:
        version = PISTON_VERSIONS[language]

    results = []

    filename = (
        "main.py"
        if language == "python"
        else "main.js"
    )

    # ===== TIMING CHECK ADDED: START =====
    total_start_time = time.time()
    test_case_number = 0
    # ===== TIMING CHECK ADDED: END =====

    for test_case in test_cases:

        # ===== TIMING CHECK ADDED: START =====
        test_case_number += 1
        piston_start_time = time.time()
        # ===== TIMING CHECK ADDED: END =====

        input_data = test_case.get(
            "input",
            "",
        )

        expected_output = str(
            test_case.get(
                "expected_output",
                "",
            )
        ).strip()

        execution_code = _prepare_code(
            code=code,
            input_data=input_data,
            language=language,
        )

        response = requests.post(
            PISTON_URL,
            json={
                "language": language,
                "version": version,
                "files": [
                    {
                        "name": filename,
                        "content": execution_code,
                    }
                ],
                "stdin": "",
            },
            timeout=10,
        )

        # ===== TIMING CHECK ADDED: START =====
        piston_time = time.time() - piston_start_time

        print(
            f"[PISTON TIMING] "
            f"Test Case {test_case_number}: "
            f"{piston_time:.2f}s"
        )
        # ===== TIMING CHECK ADDED: END =====

        response.raise_for_status()

        data = response.json()

        run = data.get(
            "run",
            {},
        )

        actual_output = run.get(
            "stdout",
            "",
        ).strip()

        error = run.get(
            "stderr",
            "",
        ).strip()

        results.append(
            {
                "input": input_data,
                "expected_output": expected_output,
                "actual_output": actual_output,
                "passed": (
                    actual_output
                    == expected_output
                ),
                "error": error,
            }
        )

    # ===== TIMING CHECK ADDED: START =====
    total_time = time.time() - total_start_time

    print(
        f"[PISTON TIMING] "
        f"Total test-case execution: "
        f"{total_time:.2f}s"
    )
    # ===== TIMING CHECK ADDED: END =====

    return results